import { SymbolInfo, TYPE_KINDS } from '../model/types';
import { GraphIndex } from '../analysis/graph';
import { ContextBuilder } from '../ai/context';

/** Deterministic ARCHITECTURE.md: every statement links back to code. AI text (optional) is clearly marked. */
export function generateArchitectureDoc(graph: GraphIndex, ctx: ContextBuilder, aiOverview?: string): string {
  const m = graph.model;
  const link = (s: SymbolInfo): string => `[${s.name}](${encodeURI(s.file)}#L${s.startLine})`;
  const out: string[] = [];
  out.push(`# Architecture — ${m.project.name}`);
  out.push('');
  out.push(`> Generated by Codebase Architecture Analyzer on ${new Date(m.analyzedAt).toLocaleString()} from static analysis of ${m.stats.sourceFiles} source files (${m.stats.types} types, ${m.stats.relationships} relationships).`);
  out.push('');
  out.push('## Overview');
  out.push('');
  if (aiOverview) {
    out.push('_AI-written summary, grounded in the facts below:_');
    out.push('');
    out.push(aiOverview.trim());
    out.push('');
  }
  out.push(`- **Languages:** ${Object.entries(m.project.languages).map(([k, v]) => `${k} (${v} files)`).join(', ')}`);
  if (m.project.frameworks.length) out.push(`- **Frameworks / libraries:** ${m.project.frameworks.join(', ')}`);
  out.push(`- **Source folders:** ${m.project.sourceFolders.map((f) => `\`${f}\``).join(', ')}`);
  out.push('');
  out.push('## Detected architecture');
  out.push('');
  out.push('| Pattern | Role | Confidence | Evidence |');
  out.push('|---|---|---|---|');
  for (const p of m.patterns) out.push(`| ${p.name} | ${p.category} | ${Math.round(p.confidence * 100)}% | ${p.evidence.join('; ').replace(/\|/g, '\\|')} |`);
  out.push('');
  out.push('## Layers');
  out.push('');
  for (const l of m.layers) out.push(`- **${l.name}** — ${l.symbols} types. ${l.evidence.join('; ')}`);
  out.push('');
  out.push('## Modules');
  out.push('');
  out.push('```mermaid');
  out.push('graph TD');
  const mid = (id: string): string => 'm' + Math.abs(hash(id));
  const shown = m.modules.filter((x) => x.layer !== 'Third-party').slice(0, 40);
  for (const mod of shown) out.push(`  ${mid(mod.id)}["${mod.name.replace(/"/g, "'")}${mod.layer ? `<br/><i>${mod.layer}</i>` : ''}"]`);
  for (const mod of shown) for (const [dep, n] of Object.entries(mod.dependsOn)) if (shown.some((s) => s.id === dep)) out.push(`  ${mid(mod.id)} -->|${n}| ${mid(dep)}`);
  out.push('```');
  out.push('');
  for (const mod of m.modules) {
    out.push(`### ${mod.name}`);
    out.push('');
    out.push(`Folder \`${mod.path}\` · ${mod.files.length} files · layer: ${mod.layer ?? 'unknown'}`);
    const deps = Object.keys(mod.dependsOn).map((d) => graph.moduleById.get(d)?.name ?? d);
    const usedBy = m.modules.filter((x) => x.dependsOn[mod.id]).map((x) => x.name);
    if (deps.length) out.push(`- Depends on: ${deps.join(', ')}`);
    if (usedBy.length) out.push(`- Used by: ${usedBy.join(', ')}`);
    const syms = mod.symbols.map((id) => graph.get(id)).filter((s): s is SymbolInfo => !!s && TYPE_KINDS.has(s.kind));
    const ranked = syms.map((s) => ({ s, n: graph.dependents(s.id).length })).sort((a, b) => b.n - a.n).slice(0, 12);
    if (ranked.length) {
      out.push('- Key types:');
      for (const { s, n } of ranked) out.push(`  - ${link(s)} (${s.kind}${s.layer ? `, ${s.layer}` : ''}) — ${n} dependent${n === 1 ? '' : 's'}`);
    }
    out.push('');
  }
  out.push('## Important types');
  out.push('');
  out.push('Ranked by number of dependents:');
  out.push('');
  for (const { s, n } of ctx.hubs(15)) out.push(`1. ${link(s)} — ${n} dependents, depends on ${graph.dependencies(s.id).length}`);
  out.push('');
  if (m.di.registrations.length) {
    out.push('## Dependency injection');
    out.push('');
    out.push(`Container(s): ${m.di.containers.join(', ')}. ${m.di.registrations.length} registrations, ${m.di.injections.length} injection points.`);
    out.push('');
    out.push('| Service | Implementation | Lifetime | Registered at |');
    out.push('|---|---|---|---|');
    for (const r of m.di.registrations.slice(0, 150)) out.push(`| ${r.service} | ${r.implementation} | ${r.lifetime ?? ''} | [${r.file}:${r.line}](${encodeURI(r.file)}#L${r.line}) |`);
    out.push('');
  }
  out.push('## Recommended reading order');
  out.push('');
  ctx.readingOrder().forEach((s, i) => out.push(`${i + 1}. ${link(s)} — ${s.layer ?? s.kind}`));
  out.push('');
  if (m.findings.length) {
    out.push('## Architecture findings');
    out.push('');
    const byKind = new Map<string, typeof m.findings>();
    for (const f of m.findings) byKind.set(f.kind, [...(byKind.get(f.kind) ?? []), f]);
    for (const [kind, fs] of byKind) {
      out.push(`### ${kind.replace(/-/g, ' ')} (${fs.length})`);
      out.push('');
      for (const f of fs.slice(0, 20)) out.push(`- **${f.title}** — ${f.detail}${f.location ? ` ([${f.location.file}:${f.location.line}](${encodeURI(f.location.file)}#L${f.location.line}))` : ''}`);
      if (fs.length > 20) out.push(`- … and ${fs.length - 20} more`);
      out.push('');
    }
  }
  return out.join('\n');
}

function hash(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
  return h;
}
